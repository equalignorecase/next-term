export type Language = "en" | "th";

export function detectDefaultLanguage(): Language {
  if (typeof navigator !== "undefined" && navigator.language) {
    if (navigator.language.toLowerCase().startsWith("th")) {
      return "th";
    }
  }
  return "en";
}

